"""Regenerate the committed Unicode tables (development tool, not a build step).

Requires Python with unicodedata 16.0.0 and regex 2025.11.3. No dependency is
needed to build or use the C library. Only Unicode 16 assigned code points
are classified. Normalization data comes from Python's Unicode database;
grapheme properties come from regex, both implementations of Unicode data.
"""
import argparse
from pathlib import Path
import unicodedata as ud
import regex

assert ud.unidata_version == '16.0.0', ud.unidata_version
assert regex.__version__ == '2025.11.3', regex.__version__
parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('--check', action='store_true')
args = parser.parse_args()
out = ['/* Generated by tools/generate_unicode.py; do not edit. */',
       '/* Unicode data: see docs/UNICODE-LICENSE.txt. */',
       '/* Unicode 16.0.0 normalization; assigned-code-point grapheme properties. */',
       '#include "rmm_unicode_data.h"',
       '',
       'const rmm_decomposition rmm_decompositions[] = {']
ccc = []
properties = []
patterns = [regex.compile(r'\A\p{gcb=' + value + r'}\Z')
            for value in ['Extend', 'SpacingMark', 'ZWJ', 'Prepend', 'Control', 'CR', 'LF']]
for cp in range(0x110000):
    ch = chr(cp)
    if ud.category(ch) == 'Cn':
        continue
    if not 0xAC00 <= cp <= 0xD7A3:
        parts = [ord(c) for c in ud.normalize('NFD', ch)]
        if parts != [cp]:
            assert len(parts) <= 4
            out.append('    {0x%X, {%s}, %d},' % (cp, ', '.join('0x%X' % p for p in parts), len(parts)))
    combining = ud.combining(ch)
    if combining:
        ccc.append((cp, combining))
    for i, pattern in enumerate(patterns):
        if pattern.fullmatch(ch):
            properties.append((cp, 1 if i < 3 else 2 if i == 3 else 3))
            break
out += ['};', 'const size_t rmm_decompositions_count = sizeof rmm_decompositions / sizeof *rmm_decompositions;']
for name, values in [('rmm_combining', ccc), ('rmm_grapheme', properties)]:
    ranges = []
    for cp, value in values:
        if ranges and ranges[-1][1] + 1 == cp and ranges[-1][2] == value:
            ranges[-1][1] = cp
        else:
            ranges.append([cp, cp, value])
    out.append('const rmm_unicode_range ' + name + '[] = {')
    out += ['    {0x%X, 0x%X, %d},' % tuple(r) for r in ranges]
    out.append('};')
    out.append('const size_t ' + name + '_count = sizeof ' + name + ' / sizeof *' + name + ';')
data = '\n'.join(out) + '\n'
path = Path(__file__).resolve().parents[1] / 'src/rmm_unicode_data.c'
if args.check:
    assert path.read_text() == data, 'Unicode tables differ'
else:
    path.write_text(data)
print('Unicode tables verified' if args.check else 'Unicode tables generated')
